            "\n"
            "# Train U-Net with Dice loss\n"
            "unet = UNet(in_ch=1, out_ch=1).to(device)\n"
            "unet_opt = optim.Adam(unet.parameters(), lr=1e-3)\n"
            "dice_crit = DiceLoss()\n"
