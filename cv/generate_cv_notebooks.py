            "\n"
            "class UNet(nn.Module):\n"
            "    \"\"\"U-Net for binary segmentation.\n"
            "\n"
            "    Architecture:\n"
            "    - Encoder: 3 DoubleConv + MaxPool stages (32->64->128 channels)\n"
