c6 = code(
    "class PursuitGridWorld:\n"
    "    # Two agents cooperating to catch one target on 6x6 grid\n"
    "    def __init__(self, size=6):\n"
    "        self.size = size\n"
    "        self.n_agents = 2\n"
    "        self.n_actions = 4  # up, down, left, right\n"
    "        self.deltas = [(-1,0),(1,0),(0,-1),(0,1)]\n"
    "\n"
    "    def reset(self):\n"
    "        # Random non-overlapping positions\n"
    "        positions = np.random.choice(self.size**2, size=3, replace=False)\n"
    "        self.agent1 = (positions[0] // self.size, positions[0] % self.size)\n"
    "        self.agent2 = (positions[1] // self.size, positions[1] % self.size)\n"
    "        self.target = (positions[2] // self.size, positions[2] % self.size)\n"
    "        return self._obs()\n"
    "\n"
    "    def _obs(self):\n"
    "        # State: (agent1_r, agent1_c, agent2_r, agent2_c, target_r, target_c)\n"
    "        return (self.agent1[0], self.agent1[1],\n"
    "                self.agent2[0], self.agent2[1],\n"
    "                self.target[0], self.target[1])\n"
    "\n"
    "    def _move(self, pos, action):\n"
    "        r, c = pos\n"
    "        dr, dc = self.deltas[action]\n"
    "        nr = max(0, min(self.size-1, r+dr))\n"
    "        nc = max(0, min(self.size-1, c+dc))\n"
    "        return (nr, nc)\n"
    "\n"
    "    def step(self, a1, a2):\n"
    "        self.agent1 = self._move(self.agent1, a1)\n"
    "        self.agent2 = self._move(self.agent2, a2)\n"
    "        # Target moves randomly\n"
    "        self.target = self._move(self.target, np.random.randint(self.n_actions))\n"
    "\n"
    "        # Catch: either agent adjacent to target\n"
    "        d1 = abs(self.agent1[0]-self.target[0]) + abs(self.agent1[1]-self.target[1])\n"
    "        d2 = abs(self.agent2[0]-self.target[0]) + abs(self.agent2[1]-self.target[1])\n"
    "        caught = (d1 <= 1) or (d2 <= 1)\n"
    "        # Bonus for both agents being close (cooperation)\n"
    "        both_close = (d1 <= 2) and (d2 <= 2)\n"
    "\n"
    "        reward = 1.0 if caught else (0.2 if both_close else -0.01)\n"
    "        return self._obs(), reward, caught\n"
    "\n"
    "\n"
    "def obs_to_idx(obs, size=6):\n"
    "    # Convert (a1r, a1c, a2r, a2c, tr, tc) to integer index\n"
    "    a1r, a1c, a2r, a2c, tr, tc = obs\n"
    "    return (a1r * size**5 + a1c * size**4 + a2r * size**3 +\n"
    "            a2c * size**2 + tr * size + tc)\n"
    "\n"
    "\n"
    "def agent_obs_idx(obs, agent_id, size=6):\n"
    "    # Individual agent observation: (agent_r, agent_c, target_r, target_c)\n"
    "    if agent_id == 0:\n"
    "        return obs[0] * size**3 + obs[1] * size**2 + obs[4] * size + obs[5]\n"
    "    else:\n"
    "        return obs[2] * size**3 + obs[3] * size**2 + obs[4] * size + obs[5]\n"
    "\n"
    "\n"
    "def run_independent_ql(n_episodes=800, alpha=0.1, gamma=0.9, eps=0.2, size=6):\n"
    "    env = PursuitGridWorld(size=size)\n"
    "    # Each agent has Q-table over local obs\n"
    "    n_local_states = size ** 4  # (ar, ac, tr, tc) per agent\n"
    "    Q1 = np.zeros((n_local_states, env.n_actions))\n"
    "    Q2 = np.zeros((n_local_states, env.n_actions))\n"
    "    catch_rates = []\n"
    "\n"
    "    for ep in range(n_episodes):\n"
    "        obs = env.reset()\n"
    "        done = False\n"
    "        t = 0\n"
    "        while not done and t < 40:\n"
    "            s1 = agent_obs_idx(obs, 0, size)\n"
    "            s2 = agent_obs_idx(obs, 1, size)\n"
    "\n"
    "            if np.random.random() < eps:\n"
    "                a1 = np.random.randint(env.n_actions)\n"
    "            else:\n"
    "                a1 = np.argmax(Q1[s1])\n"
    "            if np.random.random() < eps:\n"
    "                a2 = np.random.randint(env.n_actions)\n"
    "            else:\n"
    "                a2 = np.argmax(Q2[s2])\n"
    "\n"
    "            obs2, r, done = env.step(a1, a2)\n"
    "            s1_next = agent_obs_idx(obs2, 0, size)\n"
    "            s2_next = agent_obs_idx(obs2, 1, size)\n"
    "\n"
    "            # Independent updates: each agent uses shared reward\n"
    "            Q1[s1, a1] += alpha * (r + gamma * np.max(Q1[s1_next]) - Q1[s1, a1])\n"
    "            Q2[s2, a2] += alpha * (r + gamma * np.max(Q2[s2_next]) - Q2[s2, a2])\n"
    "            obs = obs2\n"
    "            t += 1\n"
    "        catch_rates.append(1.0 if done else 0.0)\n"
    "    return Q1, Q2, catch_rates\n"
    "\n"
    "\n"
    "print('Training independent Q-learners on pursuit...')\n"
    "np.random.seed(42)\n"
    "Q1_ind, Q2_ind, rates_ind = run_independent_ql(n_episodes=800)\n"
    "print(f'  Final 100-ep catch rate: {np.mean(rates_ind[-100:]):.2f}')\n"
)

