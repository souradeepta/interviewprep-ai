    "# Run CTDE-style cooperative Q (joint Q over agent pair actions)\n"
    "def run_ctde_pursuit(n_episodes=800, alpha=0.1, gamma=0.9, eps=0.2, size=4):\n"
    "    # Simplified 4x4 pursuit: joint state = (a1, a2, target) positions\n"
    "    # Centralized Q: Q(joint_state, a1, a2) -> scalar\n"
    "    n_actions = 4\n"
    "    deltas = [(-1,0),(1,0),(0,-1),(0,1)]\n"
    "\n"
    "    def move(pos, action):\n"
    "        r, c = pos\n"
    "        dr, dc = deltas[action]\n"
    "        return (max(0, min(size-1, r+dr)), max(0, min(size-1, c+dc)))\n"
    "\n"
    "    def to_jstate(p1, p2, target):\n"
    "        return (p1[0]*size**5 + p1[1]*size**4 +\n"
    "                p2[0]*size**3 + p2[1]*size**2 +\n"
    "                target[0]*size + target[1])\n"
    "\n"
    "    n_joint_states = size**6\n"
    "    n_joint_actions = n_actions ** 2\n"
    "    # Use dict for Q to save memory (most states unvisited)\n"
    "    Q_joint = {}\n"
    "    catch_rates = []\n"
    "\n"
    "    for ep in range(n_episodes):\n"
    "        positions = np.random.choice(size**2, size=3, replace=False)\n"
    "        p1 = (positions[0]//size, positions[0]%size)\n"
    "        p2 = (positions[1]//size, positions[1]%size)\n"
    "        target = (positions[2]//size, positions[2]%size)\n"
    "        done = False\n"
    "\n"
    "        for step in range(40):\n"
    "            js = to_jstate(p1, p2, target)\n"
    "            if js not in Q_joint:\n"
    "                Q_joint[js] = np.zeros(n_joint_actions)\n"
    "\n"
    "            if np.random.random() < eps:\n"
    "                ja = np.random.randint(n_joint_actions)\n"
    "            else:\n"
    "                ja = np.argmax(Q_joint[js])\n"
    "\n"
    "            a1 = ja // n_actions\n"
    "            a2 = ja % n_actions\n"
    "\n"
    "            p1_new = move(p1, a1)\n"
    "            p2_new = move(p2, a2)\n"
    "            # Target moves randomly\n"
    "            target = move(target, np.random.randint(n_actions))\n"
    "\n"
    "            d1 = abs(p1_new[0]-target[0]) + abs(p1_new[1]-target[1])\n"
    "            d2 = abs(p2_new[0]-target[0]) + abs(p2_new[1]-target[1])\n"
    "            caught = (d1 <= 1) or (d2 <= 1)\n"
    "            both_close = (d1 <= 2) and (d2 <= 2)\n"
    "            r = 1.0 if caught else (0.2 if both_close else -0.01)\n"
    "\n"
    "            js2 = to_jstate(p1_new, p2_new, target)\n"
    "            if js2 not in Q_joint:\n"
    "                Q_joint[js2] = np.zeros(n_joint_actions)\n"
    "\n"
    "            Q_joint[js][ja] += alpha * (r + gamma * np.max(Q_joint[js2]) - Q_joint[js][ja])\n"
    "            p1, p2 = p1_new, p2_new\n"
    "            if caught:\n"
    "                done = True\n"
    "                break\n"
    "\n"
    "        catch_rates.append(1.0 if done else 0.0)\n"
    "\n"
    "    return catch_rates\n"
    "\n"
    "\n"
    "print('Training CTDE joint Q-learning on pursuit (4x4)...')\n"
