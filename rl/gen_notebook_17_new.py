c12 = code(
    "def compute_seq_log_prob(\n"
    "    model: ToyLM, seq: list, vocab_size: int = VOCAB_SIZE\n"
    ") -> torch.Tensor:\n"
    "    \"\"\"Compute sum of log probs for a token sequence under model.\"\"\"\n"
    "    x = torch.zeros(1, vocab_size, device=device)\n"
    "    x[0, 0] = 1.0  # BOS\n"
    "    log_prob = torch.tensor(0.0, device=device)\n"
    "    for token in seq:\n"
    "        logits = model(x)\n"
    "        lp = torch.log_softmax(logits, dim=-1)[0, token]\n"
    "        log_prob = log_prob + lp\n"
    "        x = torch.zeros(1, vocab_size, device=device)\n"
    "        x[0, token] = 1.0\n"
    "    return log_prob\n"
    "\n"
    "\n"
    "def run_dpo(\n"
    "    pref_pairs: list,  # list of (winner_onehot, loser_onehot)\n"
    "    n_epochs: int = 80,\n"
    "    lr: float = 1e-3,\n"
    "    beta: float = 0.1,\n"
    ") -> tuple:\n"
    "    \"\"\"DPO training on preference data.\n"
    "    DPO loss = -log sigma(beta * [log pi(y_w)/pi_ref(y_w) - log pi(y_l)/pi_ref(y_l)])\n"
    "    Returns (dpo_policy, losses, tq_history).\n"
    "    \"\"\"\n"
    "    torch.manual_seed(42)\n"
    "    dpo_policy = ToyLM().to(device)\n"
    "    dpo_ref = ToyLM().to(device)\n"
    "    dpo_ref.load_state_dict(dpo_policy.state_dict())\n"
    "    for p in dpo_ref.parameters():\n"
    "        p.requires_grad_(False)\n"
    "    dpo_opt = torch.optim.Adam(dpo_policy.parameters(), lr=lr)\n"
    "\n"
    "    # Reconstruct token sequences from one-hot tensors for log prob computation\n"
    "    def onehot_to_seq(oh: torch.Tensor) -> list:\n"
    "        oh_np = oh.cpu().numpy()\n"
    "        seq = []\n"
    "        for i in range(SEQ_LEN):\n"
    "            seg = oh_np[i * VOCAB_SIZE:(i + 1) * VOCAB_SIZE]\n"
    "            tok = int(np.argmax(seg))\n"
    "            seq.append(tok)\n"
    "        return seq\n"
    "\n"
    "    losses_dpo = []\n"
    "    tq_history = []\n"
    "\n"
    "    for epoch in range(n_epochs):\n"
    "        batch_idx = np.random.choice(len(pref_pairs), min(32, len(pref_pairs)), replace=False)\n"
    "        batch_loss = torch.tensor(0.0, device=device)\n"
    "\n"
    "        for idx in batch_idx:\n"
    "            w_oh, l_oh = pref_pairs[idx]\n"
    "            seq_w = onehot_to_seq(w_oh)\n"
    "            seq_l = onehot_to_seq(l_oh)\n"
    "\n"
    "            log_pi_w = compute_seq_log_prob(dpo_policy, seq_w)\n"
    "            log_pi_l = compute_seq_log_prob(dpo_policy, seq_l)\n"
    "            with torch.no_grad():\n"
    "                log_ref_w = compute_seq_log_prob(dpo_ref, seq_w)\n"
    "                log_ref_l = compute_seq_log_prob(dpo_ref, seq_l)\n"
    "\n"
    "            # DPO implicit reward difference\n"
    "            reward_diff = beta * ((log_pi_w - log_ref_w) - (log_pi_l - log_ref_l))\n"
    "            loss = -torch.log(torch.sigmoid(reward_diff) + 1e-9)\n"
    "            batch_loss = batch_loss + loss\n"
    "\n"
    "        (batch_loss / len(batch_idx)).backward()\n"
    "        torch.nn.utils.clip_grad_norm_(dpo_policy.parameters(), 1.0)\n"
    "        dpo_opt.step()\n"
    "        dpo_opt.zero_grad()\n"
    "        losses_dpo.append((batch_loss / len(batch_idx)).item())\n"
    "\n"
    "        # Track true quality of samples from DPO policy\n"
    "        with torch.no_grad():\n"
    "            dpo_seqs = [sample_sequence(dpo_policy) for _ in range(32)]\n"
    "        tq_history.append(np.mean([true_reward(s) for s in dpo_seqs]))\n"
    "\n"
    "    return dpo_policy, losses_dpo, tq_history\n"
    "\n"
    "\n"
    "print('Running DPO training...')\n"
    "dpo_pol, dpo_losses, dpo_tq = run_dpo(pref_data, n_epochs=80, beta=0.1)\n"
    "print(f'DPO final true quality: {np.mean(dpo_tq[-20:]):.4f}')\n"
    "print(f'RLHF (beta=0.1) final true quality: {np.mean(true_quality_history[-20:]):.4f}')\n"
    "\n"
    "fig, axes = plt.subplots(1, 2, figsize=(12, 5))\n"
    "\n"
    "axes[0].plot(dpo_losses, color='#2c7bb6', linewidth=2, label='DPO loss')\n"
    "axes[0].set_xlabel('Epoch', fontsize=12)\n"
    "axes[0].set_ylabel('DPO Loss', fontsize=12)\n"
    "axes[0].set_title('DPO Training Loss', fontsize=12)\n"
    "axes[0].legend(); axes[0].set_facecolor('#f8f8f8'); axes[0].grid(True, alpha=0.4)\n"
    "\n"
    "# Compare quality curves: RLHF vs DPO\n"
    "axes[1].plot(true_quality_history, color='#d7191c',\n"
    "             label='RLHF (PPO, beta=0.1)', linewidth=2)\n"
    "steps_dpo = np.linspace(0, len(true_quality_history) - 1, len(dpo_tq))\n"
    "axes[1].plot(steps_dpo, dpo_tq, color='#2c7bb6',\n"
    "             label='DPO (beta=0.1)', linewidth=2, linestyle='--')\n"
    "axes[1].set_xlabel('Training Steps', fontsize=12)\n"
    "axes[1].set_ylabel('True Quality', fontsize=12)\n"
    "axes[1].set_title('True Quality: RLHF vs DPO', fontsize=12)\n"
    "axes[1].legend(); axes[1].set_facecolor('#f8f8f8'); axes[1].grid(True, alpha=0.4)\n"
    "plt.tight_layout()\n"
    "plt.savefig('/tmp/rlhf_dpo_compare.png', dpi=100, bbox_inches='tight')\n"
    "plt.show()\n"
)

