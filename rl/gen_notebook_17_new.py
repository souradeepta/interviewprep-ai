c6 = code(
    "# Toy LM: 8-token vocab, sequence length 6\n"
    "VOCAB_SIZE = 8\n"
    "SEQ_LEN = 6\n"
    "GOOD_TOKENS = {5, 6, 7}  # high-quality tokens\n"
    "\n"
    "\n"
    "class ToyLM(nn.Module):\n"
    "    \"\"\"Minimal autoregressive LM: next-token logits from one-hot current token.\"\"\"\n"
    "    def __init__(self, vocab_size: int = 8, hidden: int = 32):\n"
    "        super().__init__()\n"
    "        self.net = nn.Sequential(\n"
    "            nn.Linear(vocab_size, hidden),\n"
    "            nn.ReLU(),\n"
    "            nn.Linear(hidden, vocab_size),\n"
    "        )\n"
    "\n"
    "    def forward(self, x_onehot: torch.Tensor) -> torch.Tensor:\n"
    "        return self.net(x_onehot)  # shape: (batch, vocab_size)\n"
    "\n"
    "\n"
    "class RewardModel(nn.Module):\n"
    "    \"\"\"Reward model: takes flattened sequence one-hot, outputs scalar reward.\"\"\"\n"
    "    def __init__(self, vocab_size: int = 8, seq_len: int = 6, hidden: int = 32):\n"
    "        super().__init__()\n"
    "        self.net = nn.Sequential(\n"
    "            nn.Linear(vocab_size * seq_len, hidden),\n"
    "            nn.ReLU(),\n"
    "            nn.Linear(hidden, 1),\n"
    "        )\n"
    "\n"
    "    def forward(self, seq_onehot: torch.Tensor) -> torch.Tensor:\n"
    "        \"\"\"seq_onehot: (batch, seq_len * vocab_size)\"\"\"\n"
    "        return self.net(seq_onehot).squeeze(-1)  # (batch,)\n"
    "\n"
    "\n"
    "def sample_sequence(\n"
    "    lm: ToyLM,\n"
    "    vocab_size: int = VOCAB_SIZE,\n"
    "    seq_len: int = SEQ_LEN,\n"
    "    temperature: float = 1.0,\n"
    ") -> list:\n"
    "    \"\"\"Sample a token sequence from the LM.\"\"\"\n"
    "    seq = []\n"
    "    x = torch.zeros(1, vocab_size, device=device)\n"
    "    x[0, 0] = 1.0  # BOS token\n"
    "    for _ in range(seq_len):\n"
    "        with torch.no_grad():\n"
    "            logits = lm(x) / temperature\n"
    "        probs = torch.softmax(logits, dim=-1)\n"
    "        token = torch.multinomial(probs, 1).item()\n"
    "        seq.append(token)\n"
    "        x = torch.zeros(1, vocab_size, device=device)\n"
    "        x[0, token] = 1.0\n"
    "    return seq\n"
    "\n"
    "\n"
    "def true_reward(seq: list) -> float:\n"
    "    \"\"\"Oracle quality: proportion of good tokens in sequence.\"\"\"\n"
    "    return sum(t in GOOD_TOKENS for t in seq) / len(seq)\n"
    "\n"
    "\n"
    "def seq_to_onehot(seq: list, vocab_size: int = VOCAB_SIZE,\n"
    "                  seq_len: int = SEQ_LEN) -> torch.Tensor:\n"
    "    \"\"\"Convert token list to flattened one-hot tensor.\"\"\"\n"
    "    x = torch.zeros(seq_len * vocab_size, device=device)\n"
    "    for i, t in enumerate(seq):\n"
    "        x[i * vocab_size + t] = 1.0\n"
    "    return x\n"
    "\n"
    "\n"
    "# ---- Stage 1: Train Reward Model from pairwise preferences ----\n"
    "torch.manual_seed(42)\n"
    "policy = ToyLM().to(device)\n"
    "ref_policy = ToyLM().to(device)\n"
    "# Copy policy weights to reference (frozen)\n"
    "ref_policy.load_state_dict(policy.state_dict())\n"
    "for p in ref_policy.parameters():\n"
    "    p.requires_grad_(False)\n"
    "\n"
    "rm = RewardModel().to(device)\n"
    "rm_optimizer = torch.optim.Adam(rm.parameters(), lr=1e-3)\n"
    "\n"
    "# Generate preference pairs from initial policy\n"
    "pref_data = []\n"
    "with torch.no_grad():\n"
    "    for _ in range(600):\n"
    "        seqA = sample_sequence(policy)\n"
    "        seqB = sample_sequence(policy)\n"
    "        rA, rB = true_reward(seqA), true_reward(seqB)\n"
    "        if abs(rA - rB) < 1e-6:\n"
    "            continue  # skip ties\n"
    "        if rA > rB:\n"
    "            pref_data.append((seq_to_onehot(seqA), seq_to_onehot(seqB)))\n"
    "        else:\n"
    "            pref_data.append((seq_to_onehot(seqB), seq_to_onehot(seqA)))\n"
    "\n"
    "print(f'Collected {len(pref_data)} preference pairs')\n"
    "\n"
    "# Train RM: Bradley-Terry loss\n"
    "rm_losses = []\n"
    "for epoch in range(150):\n"
    "    batch_size = min(64, len(pref_data))\n"
    "    idx = np.random.choice(len(pref_data), batch_size, replace=False)\n"
    "    batch_w = torch.stack([pref_data[i][0] for i in idx])\n"
    "    batch_l = torch.stack([pref_data[i][1] for i in idx])\n"
    "    r_w = rm(batch_w)\n"
    "    r_l = rm(batch_l)\n"
    "    loss = -torch.log(torch.sigmoid(r_w - r_l) + 1e-9).mean()\n"
    "    rm_optimizer.zero_grad()\n"
    "    loss.backward()\n"
    "    rm_optimizer.step()\n"
    "    rm_losses.append(loss.item())\n"
    "\n"
    "print(f'RM training complete. Final loss: {rm_losses[-1]:.4f}')\n"
    "\n"
    "# ---- Stage 2: PPO-style fine-tuning with KL penalty ----\n"
    "policy_opt = torch.optim.Adam(policy.parameters(), lr=1e-3)\n"
    "kl_beta = 0.1\n"
    "reward_history = []\n"
    "kl_history = []\n"
    "true_quality_history = []\n"
    "\n"
    "for step in range(200):\n"
    "    # Sample batch of sequences\n"
    "    seqs = [sample_sequence(policy) for _ in range(16)]\n"
    "\n"
    "    # RM rewards (no grad through RM)\n"
    "    with torch.no_grad():\n"
    "        rm_rewards = torch.stack(\n"
    "            [rm(seq_to_onehot(s).unsqueeze(0)).squeeze() for s in seqs]\n"
    "        )\n"
    "\n"
    "    # REINFORCE with KL penalty\n"
    "    policy_opt.zero_grad()\n"
    "    total_loss = torch.tensor(0.0, device=device)\n"
    "\n"
    "    for seq in seqs:\n"
    "        x = torch.zeros(1, VOCAB_SIZE, device=device)\n"
    "        x[0, 0] = 1.0  # BOS\n"
    "        log_probs = []\n"
    "        ref_log_probs = []\n"
    "        for token in seq:\n"
    "            logits = policy(x)\n"
    "            with torch.no_grad():\n"
    "                ref_logits = ref_policy(x)\n"
    "            lp = torch.log_softmax(logits, dim=-1)[0, token]\n"
    "            ref_lp = torch.log_softmax(ref_logits, dim=-1)[0, token]\n"
    "            log_probs.append(lp)\n"
    "            ref_log_probs.append(ref_lp)\n"
    "            x = torch.zeros(1, VOCAB_SIZE, device=device)\n"
    "            x[0, token] = 1.0\n"
    "\n"
    "        log_prob = sum(log_probs)\n"
    "        ref_log_prob = sum(ref_log_probs).detach()\n"
    "        kl = log_prob - ref_log_prob  # KL approx per sequence\n"
    "\n"
    "        with torch.no_grad():\n"
    "            r_rm = rm(seq_to_onehot(seq).unsqueeze(0)).squeeze()\n"
    "        # PPO objective: maximize (reward - beta * KL)\n"
    "        total_loss = total_loss + (-(r_rm - kl_beta * kl) * log_prob)\n"
    "\n"
    "    (total_loss / len(seqs)).backward()\n"
    "    torch.nn.utils.clip_grad_norm_(policy.parameters(), 1.0)\n"
    "    policy_opt.step()\n"
    "\n"
    "    # Track metrics\n"
    "    with torch.no_grad():\n"
    "        avg_rm_reward = rm_rewards.mean().item()\n"
    "    avg_true_quality = np.mean([true_reward(s) for s in seqs])\n"
    "    reward_history.append(avg_rm_reward)\n"
    "    true_quality_history.append(avg_true_quality)\n"
    "\n"
    "print(f'PPO (beta=0.1) - Final RM reward: {np.mean(reward_history[-20:]):.4f}')\n"
    "print(f'PPO (beta=0.1) - Final true quality: {np.mean(true_quality_history[-20:]):.4f}')\n"
)

