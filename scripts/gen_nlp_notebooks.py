            "        topk: number of candidates to return\n"
            "    Returns:\n"
            "        list of (word, similarity) tuples\n"
            "    \"\"\"\n"
            "    query = W_in[w2i[a]] - W_in[w2i[b]] + W_in[w2i[c]]\n"
            "    sims = [\n"
            "        (i2w[i], cosine_sim(query, W_in[i]))\n"
            "        for i in range(V)\n"
            "        if i2w[i] not in {a, b, c}\n"
            "    ]\n"
            "    return sorted(sims, key=lambda x: -x[1])[:topk]\n"
            "\n"
            "\n"
            "print('\\nAnalogy: king - man + woman')\n"
            "for word, sim in analogy('king', 'man', 'woman'):\n"
            "    print(f'  {word:12s} sim={sim:.4f}')\n"
