            "        end = min(len(idx_tokens), pos + window + 1)\n"
            "        for ctx_pos in range(start, end):\n"
            "            if ctx_pos != pos:\n"
            "                pairs.append((center, idx_tokens[ctx_pos]))\n"
            "    return pairs\n"
