            "        Args:\n"
            "            centers: (B,) center word indices\n"
            "            contexts: (B,) positive context indices\n"
            "            negatives: (B, K) negative sample indices\n"
            "        Returns:\n"
            "            scalar loss\n"
            "        \"\"\"\n"
            "        v_c = self.embed_in(centers)      # (B, D)\n"
            "        v_ctx = self.embed_out(contexts)  # (B, D)\n"
            "        v_neg = self.embed_out(negatives) # (B, K, D)\n"
            "        # positive score: sum(v_c * v_ctx, dim=-1)\n"
            "        pos_score = torch.sum(v_c * v_ctx, dim=-1)  # (B,)\n"
            "        # negative scores: bmm for batch dot product\n"
            "        neg_scores = torch.bmm(\n"
            "            v_neg, v_c.unsqueeze(-1)\n"
            "        ).squeeze(-1)  # (B, K)\n"
            "        # binary cross-entropy form\n"
            "        loss_pos = nn.functional.logsigmoid(pos_score)\n"
